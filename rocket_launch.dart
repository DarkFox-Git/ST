void main() {
  for (int i = 5; i >= 1; i--) { //Воспроизведит цикл, который каждый раз отнимает значение переменной "i" по -1, создавая отсчет
    print(i); //Выводит отсчет коммандную строку с каждым новым воспроизведением цикла
  }
  print('Поехали!'); //Выводит финальное сообщение после завершиния цикла
}